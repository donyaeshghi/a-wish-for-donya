-- این SQL را در Supabase Dashboard > SQL Editor اجرا کن.
create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  sender_name text,
  message text not null check (char_length(message) between 1 and 1000),
  created_at timestamptz not null default now(),
  constraint sender_name_length check (sender_name is null or char_length(sender_name) <= 50)
);

alter table public.wishes enable row level security;

-- هر بازدیدکننده می‌تواند یک آرزو بفرستد.
drop policy if exists "Anyone can send a wish" on public.wishes;
create policy "Anyone can send a wish"
on public.wishes for insert
to anon, authenticated
with check (
  char_length(message) between 1 and 1000
  and (sender_name is null or char_length(sender_name) <= 50)
);

-- فقط کاربران واردشده می‌توانند آرزوها را بخوانند.
-- در تنظیمات Auth ثبت‌نام عمومی را خاموش کن و فقط حساب خودت را بساز.
drop policy if exists "Only signed-in admin can read wishes" on public.wishes;
create policy "Only signed-in admin can read wishes"
on public.wishes for select
to authenticated
using (true);

-- هیچ policy برای anon در SELECT وجود ندارد؛ بازدیدکنندگان نمی‌توانند آرزوها را بخوانند.
-- در این نسخه امکان حذف از پنل اضافه نشده تا پیام‌ها تصادفی پاک نشوند.
